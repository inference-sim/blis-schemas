// rulesFile writes every registered pack: its rules, with the severities each can report
// and the reason it exists, then the values it accepts.
func rulesFile(root string) (file, error) {
	var b bytes.Buffer
	b.WriteString(header)
	// Newest release first, compared numerically: as strings, 0.100.0 sorts before 0.29.0.
	versions := rules.Versions()
	sort.SliceStable(versions, func(i, j int) bool { return versionLess(versions[j], versions[i]) })
	for _, v := range versions {
		p := rules.Lookup(v)
		// Severities are read from the source of the package that defines this pack's
		// rules, so two packs that report one rule name at different severities are each
		// described correctly.
		dir, err := packDir(p)
		if err != nil {
			return file{}, err
		}
		sev, err := ruleSeverities(filepath.Join(root, dir))
		if err != nil {
			return file{}, err
		}
		fmt.Fprintf(&b, "## Engine %s\n\n", v)
		fmt.Fprintf(&b, "### Rules\n\n")
		for _, r := range p.Rules {
			s := sev[r.Name]
			if len(s) == 0 {
				return file{}, fmt.Errorf("rule %q reports through no RuleErrorf or RuleWarnf call docgen can find", r.Name)
			}
			fmt.Fprintf(&b, "`%s`\n:   *%s.* %s\n\n", r.Name, strings.Join(s, " or "), sentence(r.Because))
		}
		fmt.Fprintf(&b, "### Accepted values\n\n")
		fmt.Fprintf(&b, "| Pack field | Governs | Value |\n|---|---|---|\n")
		pv := reflect.ValueOf(*p)
		pt := pv.Type()
		for i := 0; i < pt.NumField(); i++ {
			name := pt.Field(i).Name
			if name == "Version" || name == "Rules" {
				continue
			}
			label, ok := packFields[name]
			if !ok {
				return file{}, fmt.Errorf("rules.Pack.%s has no label in docgen's packFields", name)
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s |\n", name, label, render(pv.Field(i)))
		}
		b.WriteString("\n")
	}
	return file{path: outDir + "/rules.md", content: b.Bytes()}, nil
}

// packDir returns the repository-relative directory of the package whose functions are the
// pack's rule checks. Every rule of one pack must be defined in one package.
func packDir(p *rules.Pack) (string, error) {
	const module = "github.com/inference-sim/blis-schemas/"
	dir := ""
	for _, r := range p.Rules {
		fn := runtime.FuncForPC(reflect.ValueOf(r.Check).Pointer())
		if fn == nil {
			return "", fmt.Errorf("pack %s: rule %q has no resolvable Check function", p.Version, r.Name)
		}
		// A closure's name is "<import path>.<function>.func<n>". The import path ends at
		// the first dot after its last slash.
		name := strings.TrimPrefix(fn.Name(), module)
		slash := strings.LastIndex(name, "/")
		d := name[:slash+1+strings.Index(name[slash+1:], ".")]
		if dir == "" {
			dir = d
		} else if d != dir {
			return "", fmt.Errorf("pack %s defines rules in both %s and %s", p.Version, dir, d)
		}
	}
	return filepath.FromSlash(dir), nil
}

// versionLess compares dotted version strings field by field, numerically where both
// fields are numbers.
func versionLess(a, b string) bool {
	as, bs := strings.Split(a, "."), strings.Split(b, ".")
	for i := 0; i < len(as) && i < len(bs); i++ {
		x, errX := strconv.Atoi(as[i])
		y, errY := strconv.Atoi(bs[i])
		switch {
		case errX == nil && errY == nil && x != y:
			return x < y
		case (errX != nil || errY != nil) && as[i] != bs[i]:
			return as[i] < bs[i]
		}
	}
	return len(as) < len(bs)
}

// render prints a pack value: a set as its sorted members, a scalar as itself.
func render(v reflect.Value) string {
	switch v.Kind() {
	case reflect.Map:
		if v.Type().Elem().Kind() != reflect.Bool {
			return fmt.Sprintf("(a %s, which docgen cannot render)", v.Type())
		}
		keys := v.MapKeys()
		var members []string
		for _, k := range keys {
			if v.MapIndex(k).Bool() {
				members = append(members, fmt.Sprint(k.Interface()))
			}
		}
		if v.Type().Key().Kind() == reflect.Int {
			sort.Slice(members, func(i, j int) bool {
				a, _ := strconv.Atoi(members[i])
				c, _ := strconv.Atoi(members[j])
				return a < c
			})
		} else {
			sort.Strings(members)
		}
		for i, m := range members {
			members[i] = "`" + m + "`"
		}
		return strings.Join(members, " ")
	default:
		return "`" + fmt.Sprint(v.Interface()) + "`"
	}
}

// ruleSeverities scans one package's non-test files for RuleErrorf and RuleWarnf calls whose
// first argument is a rule name, and returns the severities each name can report.
func ruleSeverities(dir string) (map[string][]string, error) {
	found := map[string]map[string]bool{}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	for _, e := range entries {
		path := filepath.Join(dir, e.Name())
		if e.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
		if err != nil {
			return nil, err
		}
		ast.Inspect(f, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok || len(call.Args) == 0 {
				return true
			}
			sel, ok := call.Fun.(*ast.SelectorExpr)
			if !ok {
				return true
			}
			var s string
			switch sel.Sel.Name {
			case "RuleErrorf":
				s = "error"
			case "RuleWarnf":
				s = "warning"
			default:
				return true
			}
			lit, ok := call.Args[0].(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				return true
			}
			name, err := strconv.Unquote(lit.Value)
			if err != nil {
				return true
			}
			if found[name] == nil {
				found[name] = map[string]bool{}
			}
			found[name][s] = true
			return true
		})
	}
	out := map[string][]string{}
	for name, set := range found {
		for _, s := range []string{"error", "warning"} {
			if set[s] {
				out[name] = append(out[name], s)
			}
		}
	}
	return out, nil
}

// sentence capitalizes a Because clause and ends it with a period, since the source
// writes each as a clause that follows "because".
func sentence(s string) string {
	s = strings.TrimSpace(s)
	if s == "" {
		return s
	}
	s = strings.ToUpper(s[:1]) + s[1:]
	if !strings.HasSuffix(s, ".") {
		s += "."
	}
	return s
}
